#: Множество разделителей, собранное из диапазонов один раз при импорте.
_FTS_SEPARATORS = frozenset(
    chr(code)
    for start, end in _FTS_SEPARATOR_RANGES
    for code in range(start, end + 1)
)


def query_tokens(query: str) -> tuple[str, ...]:
    """Разбить нормализованный запрос на токены — лексика индекса (§8).

    Границы слов задают фактические таблицы токенизатора FTS5
    ``unicode61`` (см. модуль): разделители — ``_FTS_SEPARATORS``; всё
    остальное входит в токен, при этом латинские диакритики
    ``_FTS_CONTINUE_ONLY`` продолжают уже начатое слово и отбрасываются
    перед его началом — ровно как это делает токенизатор индекса.
    Порядок токенов сохраняется, дубликаты не удаляются: повтор слова в
    запросе не меняет множество совпадений, поскольку все слова
    обязательны.
    """
    tokens: list[str] = []
    current: list[str] = []
    for char in normalize(query):
        if char in _FTS_SEPARATORS:
            if current:
                tokens.append("".join(current))
                current = []
        elif current or char not in _FTS_CONTINUE_ONLY:
            current.append(char)
    if current:
        tokens.append("".join(current))
    return tuple(tokens)


def build_match(tokens: tuple[str, ...]) -> str:
    """Собрать безопасное FTS5 MATCH-выражение из токенов.

    Каждый токен — фраза в двойных кавычках с ``*`` (префикс слова); фразы
    соединяются ``AND``. Токены не могут содержать разделители, поэтому
    пользовательский синтаксис FTS (операторы, скобки, column filters,
    ``*``) исполниться не может; кавычки внутри токена удваиваются на
    случай будущих изменений токенизации.
    """
    phrases = []
    for token in tokens:
        escaped = token.replace('"', '""')
        phrases.append(f'"{escaped}"*')
    return " AND ".join(phrases)
