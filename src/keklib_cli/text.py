"""Нормализация текста и лексика запроса для поиска (спецификация §8).

Единая нормализация применяется к авторам, названиям и словам запроса:
Unicode NFKC, ``casefold()`` и замена «ё» на «е». Порядок шагов важен:
``casefold()`` переводит «Ё» в «ё», поэтому замена выполняется последней.
Исходный текст для отображения не изменяется.

Канонизация спорных кодовых точек (исправительная волна CI, 2026-10-19):
``normalize`` дополнительно вырезает U+FFFE, U+FFFF и весь диапазон
суррогатов 0xD800..0xDFFF — симметрично при индексировании и разборе
запроса. Причина: статус U+FFFE/U+FFFF в токенизаторе ``unicode61``
менялся между версиями SQLite (3.45.1 сборок CI завершает ими слово,
3.54.0 оставляет внутри токена — подтверждено живым зондом ``fts5vocab``
на обеих версиях), а суррогаты непредставимы в строгом UTF-8 каталога и
не могут попасть в индекс валидно. Вырезание делает лексику запроса и
индекса идентичной на любом runtime: FTS эти кодовые точки вообще не
видит. Эти же точки объявлены разделителями в ``_FTS_SEPARATORS``
(защита на случай появления в обход ``normalize``); прочие форматные
символы (Cf, например U+2060) НЕ вырезаются — их токенизатор обрабатывает
единообразно.

Токенизация запроса — точное лексическое зеркало фактического
токенизатора индекса, FTS5 ``unicode61`` с ``remove_diacritics 0``
(таблицы Unicode 6.1, поставляются с SQLite и не зависят от версии
Python). Разбиение запроса ``str.isalnum`` расходилось с этим
токенизатором на combining-метках (ма́стер, casefold(İstanbul), q́abc)
и на незакреплённых кодпоинтах его таблиц: полное видимое название
из выдачи не находило саму книгу (финальный обзор, F2). Поэтому
границы слов запроса задают фактические таблицы FTS:

- разделители (``_FTS_SEPARATORS``) — кодовые точки, которыми
  токенизатор заканчивает слово: назначенные в Unicode 6.1 знаки
  пунктуации/символы/пробельные, включая Mc-метки письменностей
  Индии и иврита; всё остальное кодовое пространство (буквы, цифры,
  combining-метки Mn, незакреплённые кодпоинты) входит в токен;
- ``_FTS_CONTINUE_ONLY`` — латинские диакритики, которые
  продолжают начатый токен, но никогда его не начинают
  (``sqlite3Fts5UnicodeIsdiacritic``; ``remove_diacritics 0``
  сохраняет их внутри токена).

Оба множества выведены полным перебором фактического токенизатора
SQLite 3.54 (зонд через ``fts5vocab``, see
``tests/test_search.py::TokenizerAlignmentTests``); тест живой
сверкой фиксирует таблицы против текущего SQLite, поэтому дрейф
таблиц в будущих версиях SQLite останавливается громким отказом
теста, а не молчаливым расхождением запроса с индексом. Кодовые точки
0x20, полный диапазон суррогатов 0xD800..0xDFFF и U+FFFE/U+FFFF
добавлены в разделители явно и исключены из живой сверки: пробел
разделяет слова, а канонизированные точки вырезаются до FTS (см.
``CanonicalNoncharacterTests``) — их контракт держится не версией
SQLite, а самой таблицей и симметрией нормализации.
"""

from __future__ import annotations

import unicodedata


def normalize(text: str) -> str:
    """Вернуть нормализованную форму ``text`` для индексирования и поиска.

    NFKC → casefold → ё→е → вырезание канонизированных кодовых точек
    (U+FFFE/U+FFFF и суррогаты 0xD800..0xDFFF, см. модуль): спорные для
    токенизатора точки не доходят ни до индекса, ни до MATCH — лексика
    обеих сторон совпадает на любой версии SQLite.
    """
    return (
        unicodedata.normalize("NFKC", text)
        .casefold()
        .replace("ё", "е")
        .translate(_CANONICAL_REMOVED)
    )


